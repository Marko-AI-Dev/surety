// Writes .env.api with fresh random API tokens: one per role (lead, sourcing, negotiator, view) and
// one per supplier wallet. Supplier addresses come from --suppliers a,b,c or the supplier directory
// (fixtures/sourcing/directory.json). Never prints a token; refuses to replace .env.api without --force.
// Run: pnpm api:tokens [--force] [--suppliers rA,rB]
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { Address } from "@surety/contracts";

export function renderApiEnv(supplierAddresses: string[], token: () => string): string {
  for (const a of supplierAddresses) {
    if (!Address.safeParse(a).success) throw new Error(`${a} is not an XRPL address`);
  }
  const suppliers = Object.fromEntries(supplierAddresses.map((a) => [a, token()]));
  return [
    "# Surety API tokens. Generated by pnpm api:tokens; never commit or print.",
    `API_TOKEN_LEAD=${token()}`,
    `API_TOKEN_SOURCING=${token()}`,
    `API_TOKEN_NEGOTIATOR=${token()}`,
    `API_TOKEN_VIEW=${token()}`,
    `API_SUPPLIER_TOKENS=${JSON.stringify(suppliers)}`,
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const root = resolve(import.meta.dirname, "../../..");
  const out = resolve(root, ".env.api");
  if (existsSync(out) && !process.argv.includes("--force")) {
    console.error(".env.api already exists; pass --force to replace it (agents holding the old tokens stop working).");
    process.exit(1);
  }
  const flag = process.argv.indexOf("--suppliers");
  const directory = resolve(root, "fixtures/sourcing/directory.json");
  const addresses =
    flag !== -1
      ? (process.argv[flag + 1] ?? "").split(",").filter(Boolean)
      : existsSync(directory)
        ? (JSON.parse(readFileSync(directory, "utf8")) as { address: string }[]).map((e) => e.address)
        : [];
  writeFileSync(out, renderApiEnv(addresses, () => randomBytes(48).toString("base64url")), { mode: 0o600 });
  console.log(`Wrote .env.api: 4 role tokens and ${addresses.length} supplier tokens (values not shown).`);
}
